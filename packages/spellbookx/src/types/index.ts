/**
 * @file index.ts
 * Core TypeScript types and interfaces for the Spellbookx CLI.
 */

/**
 * Identifier for supported Spellbookx tool configurations.
 */
export type ToolId = 'commitlint' | 'cspell' | 'eslint' | 'prettier';

/**
 * Supported package managers for dependency installation.
 */
export type PackageManager = 'bun' | 'npm' | 'pnpm' | 'yarn';

/**
 * Supported Git hook managers wired up during commitlint setup.
 */
export type HookManager = 'husky' | 'lefthook';

/**
 * Prettier preset identifiers offered by `prettier-config-spellbookx`.
 */
export type PrettierConfigId = 'base' | 'recommended';

/**
 * ESLint preset identifiers offered by `eslint-plugin-spellbookx`.
 */
export type ESLintConfigId =
  | 'all'
  | 'astro'
  | 'base'
  | 'javascript'
  | 'json'
  | 'markdown'
  | 'node'
  | 'react'
  | 'recommended'
  | 'recommended-spellcheck'
  | 'strict'
  | 'svelte';

/**
 * Choices gathered from the user (or defaults) that influence generated files.
 */
export interface ResolvedChoices {
  prettierConfig: PrettierConfigId;
  eslintConfig: ESLintConfigId;
  hookManager: HookManager;
}

/**
 * Metadata for a configuration file generated by a tool setup.
 */
export interface ConfigFile {
  path: string;
  content: string;
  /**
   * Optional POSIX file mode (e.g. 0o755 for executable Git hooks).
   */
  mode?: number;
}

/**
 * Context passed to tool resolvers to produce context-aware files and scripts.
 */
export interface ToolContext {
  choices: ResolvedChoices;
  packageManager: PackageManager;
}

/**
 * Specification and assets defining a Spellbookx tool integration.
 */
export interface ToolDefinition {
  id: ToolId;
  title: string;
  description: string;
  defaultChecked: boolean;
  getDependencies: (context: ToolContext) => string[];
  getConfigFiles: (context: ToolContext) => ConfigFile[];
  getScripts?: (context: ToolContext) => Record<string, string>;
  getExtraPackageJson?: (context: ToolContext) => Record<string, unknown>;
}

/**
 * Options passed to the Spellbookx setup runner.
 */
export interface SetupOptions {
  cwd?: string;
  tools?: ToolId[];
  packageManager?: PackageManager;
  skipInstall?: boolean;
  silent?: boolean;
  interactive?: boolean;
  prettierConfig?: PrettierConfigId;
  eslintConfig?: ESLintConfigId;
  hookManager?: HookManager;
}

/**
 * Summary of actions performed during toolchain setup.
 */
export interface SetupResult {
  selectedTools: ToolId[];
  packageManager: PackageManager;
  choices: ResolvedChoices;
  installedDependencies: string[];
  createdFiles: string[];
}
